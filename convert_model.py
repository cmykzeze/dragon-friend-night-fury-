import re, ast, sys, math
SRC = sys.argv[1]
OUT = sys.argv[2]
src = open(SRC, encoding="utf-8").read()
ctor = src[src.index("public ModelNightFury()"):]
f = lambda s: float(s.replace("F", "").replace("f", ""))
num = r"(-?[0-9.]+(?:E-?[0-9]+)?)[Ff]?"

nodes, order = {}, []
parent = {}
for m in re.finditer(r"(\w+) = new (ModelRenderer|WingRenderer)\(model(?:, (-?\d+), (-?\d+))?\);", ctor):
    n = m.group(1)
    nodes[n] = dict(name=n, uv=(int(m.group(3) or 0), int(m.group(4) or 0)), boxes=[], pos=(0, 0, 0), rot=(0, 0, 0), wing=(m.group(2) == "WingRenderer"))
    order.append(n)
for m in re.finditer(r"(\w+)\.addBox\(" + r",\s*".join([num] * 6) + r"\);", ctor):
    nodes[m.group(1)]["boxes"].append(tuple(f(m.group(i)) for i in range(2, 8)))
for m in re.finditer(r"(\w+)\.setRotationPoint\(" + r",\s*".join([num] * 3) + r"\);", ctor):
    nodes[m.group(1)]["pos"] = tuple(f(m.group(i)) for i in range(2, 5))
for m in re.finditer(r"setRotation\((\w+),\s*" + r",\s*".join([num] * 3) + r"\);", ctor):
    nodes[m.group(1)]["rot"] = tuple(f(m.group(i)) for i in range(2, 5))
for m in re.finditer(r"(\w+)\.addChild\((\w+)\);", ctor):
    parent[m.group(2)] = m.group(1)
assert "NightFury" in nodes and "NightFury" not in parent
missing = [n for n in nodes if n != "NightFury" and n not in parent]
assert not missing, missing

children = {}
for n in order:
    if n in parent:
        children.setdefault(parent[n], []).append(n)

def path(n):
    p = [n]
    while p[-1] in parent:
        p.append(parent[p[-1]])
    return "/".join(reversed(p))

# ---- animations ----
def get_anim(var):
    i = ctor.index(var + " = new Animation(")
    # walk backwards to the enclosing block start
    start = ctor.rindex("ModelRenderer[] components", 0, i)
    block = ctor[start:i]
    comps = re.search(r"components = \{(.*?)\};", block, re.S).group(1)
    comps = [c.strip() for c in comps.split(",") if c.strip()]
    dur = int(re.search(r"int duration = (\d+);", block).group(1))
    data = re.search(r"data = (\{.*\});", block, re.S).group(1)
    data = re.sub(r"(\d)f", r"\1", data).replace("{", "[").replace("}", "]")
    data = ast.literal_eval(data)
    assert len(data) == len(comps), (var, len(data), len(comps))
    return comps, dur, data

anims = {"FLYING": get_anim("flying"), "IDLE": get_anim("idle2")}
for k, (cs, _, _) in anims.items():
    for c in cs:
        assert c in nodes, (k, c)

# wing subtree
wing_set = set()
def collect(n):
    wing_set.add(n)
    for c in children.get(n, []):
        collect(c)
collect("wing")

def jf(x):
    s = repr(float(x))
    return s + "f"

out = []
w = out.append
w("package com.httymd.client.model;")
w("")
w("// GENERATED by tools/convert_model.py from the original HTTYMD 1.7.10 ModelNightFury.java.")
w("// Model shape, pivots, texture offsets and animation keyframes come from the original HTTYMD mod")
w("// (c) The HTTYMD Team - used with permission. See CREDITS.md.")
w("// Do not edit by hand; re-run the converter instead.")
w("")
w("import java.util.LinkedHashMap;")
w("import java.util.Map;")
w("")
w("import net.minecraft.client.model.geom.builders.CubeListBuilder;")
w("import net.minecraft.client.model.geom.builders.LayerDefinition;")
w("import net.minecraft.client.model.geom.builders.MeshDefinition;")
w("import net.minecraft.client.model.geom.builders.PartDefinition;")
w("import net.minecraft.client.model.geom.PartPose;")
w("")
w("public final class NightFuryModelData {")
w("    private NightFuryModelData() {}")
w("")
w("    public static final int TEX_SIZE = 512;")
w("    public static final String LEFT_PREFIX = \"L_\";")
w("")
w("    /** name -> path from the model root, e.g. NightFury/body/tail */")
w("    public static final Map<String, String> PATHS = new LinkedHashMap<>();")
w("    /** name -> {x, y, z, rotX, rotY, rotZ} (pixels / radians) */")
w("    public static final Map<String, float[]> BASE = new LinkedHashMap<>();")
w("    static {")
for n in order:
    nd = nodes[n]
    p = path(n)
    w(f'        PATHS.put("{n}", "{p}");')
    w(f'        BASE.put("{n}", new float[] {{{", ".join(jf(v) for v in nd["pos"] + nd["rot"])}}});')
    if n in wing_set:
        # build left path by prefixing every wing-subtree node
        parts = path(n).split("/")
        parts = [("L_" + x) if x in wing_set else x for x in parts]
        w(f'        PATHS.put("L_{n}", "{"/".join(parts)}");')
        w(f'        BASE.put("L_{n}", BASE.get("{n}"));')
w("    }")
w("")
w("    public static LayerDefinition createLayer() {")
w("        MeshDefinition mesh = new MeshDefinition();")
w("        PartDefinition root = mesh.getRoot();")
def build(n, parent_var, prefix, mirror):
    nd = nodes[n]
    name = prefix + n if (n in wing_set and prefix) else n
    var = "p_" + name
    cube = "CubeListBuilder.create()"
    if nd["boxes"]:
        cube += f".texOffs({nd['uv'][0]}, {nd['uv'][1]})"
        for b in nd["boxes"]:
            cube += f".addBox({', '.join(jf(v) for v in b)})"
    px, py, pz = nd["pos"]; rx, ry, rz = nd["rot"]
    w(f'        PartDefinition {var} = {parent_var}.addOrReplaceChild("{name}", {cube}, PartPose.offsetAndRotation({jf(px)}, {jf(py)}, {jf(pz)}, {jf(rx)}, {jf(ry)}, {jf(rz)}));')
    for c in children.get(n, []):
        build(c, var, prefix, mirror)
def build_root(n, parent_var, prefix):
    build(n, parent_var, prefix, False)
# NightFury is the single top node; its subtree contains wing at body level.
# emit normal tree, then the left-wing duplicate under wing's parent.
build("NightFury", "root", "", False)
wp = parent["wing"]
w(f'        // left wing = duplicate of the wing subtree, mirrored at render time (xScale = -1) like the original WingRenderer')
build("wing", "p_" + wp, "L_", True)
w(f"        return LayerDefinition.create(mesh, TEX_SIZE, TEX_SIZE);")
w("    }")
w("")
w("    /** Animation: part names, duration in ms, data[part][attr][frame]; attr 0-2 = x,y,z px; 3-5 = rotX,Y,Z degrees. */")
for key, (comps, dur, data) in anims.items():
    w(f"    public static final int {key}_DURATION_MS = {dur};")
    w(f"    public static final String[] {key}_PARTS = {{{', '.join(chr(34)+c+chr(34) for c in comps)}}};")
    w(f"    public static final float[][][] {key}_DATA = {{")
    for comp in data:
        w("        {")
        for attr in comp:
            w("            {" + ", ".join(jf(v) for v in attr) + "},")
        w("        },")
    w("    };")
    w("")
w("}")
open(OUT, "w", encoding="utf-8").write("\n".join(out) + "\n")
print("nodes", len(nodes), "wing subtree", len(wing_set), {k: (len(v[0]), v[1], len(v[2][0][0])) for k, v in anims.items()})
print("wing parent:", wp)
